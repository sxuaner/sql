

--  what is SQL procedure?
--  A SQL procedure is a stored program that can be executed in the database. 
--  It is a set of SQL statements that perform a specific task, such as retrieving data, updating records, or performing calculations. 
--  Procedures can accept parameters, execute complex logic, and return results. 
--  !!!!!!!!!! They are used to encapsulate business logic and improve code reusability and maintainability.  !!!!!!!!!!!!!!!!!!!!!
--  Procedures are typically created using the CREATE PROCEDURE statement and can be executed using the EXECUTE or CALL statement.
--  Procedures can be written in SQL or PL/SQL, which is Oracle's procedural extension to SQL.

--  waht is PL/SQL procedure?
--  PL/SQL procedure is a block of code that can be executed in the Oracle database
--  It is a set of SQL statements and PL/SQL code that can perform complex operations, such as data manipulation, control flow, and exception handling.
--  PL/SQL procedures can accept parameters, execute complex logic, and return results.

-- is PL/SQL only for Oracle?
--  PL/SQL is Oracle's procedural extension to SQL, so it is primarily used in Oracle databases.
--  However, other database systems may have similar procedural extensions, such as T-SQL in Microsoft SQL Server or PL/pgSQL in PostgreSQL.